let explorerRows = [], explorerShown = 100;
document.getElementById("explorer-form").addEventListener("submit", e => {
  e.preventDefault();
  const v = id => document.getElementById(id).value;
  const text = v("x-text").trim().toLowerCase();
  const instOk = CUTOFFS.institutes.map(([name, city, state]) =>
    (!v("x-state") || state === v("x-state")) &&
    (!text || `${name} ${city || ""} ${state || ""}`.toLowerCase().includes(text)));
  explorerRows = CUTOFFS.rows.filter(r => {
    const src = SOURCES[r[R.SRC]];
    return instOk[r[R.INST]]
      && courseMatches(r[R.COURSE], v("x-program"), v("x-specialty"))
      && (v("x-quota") === "" || r[R.QUOTA] === Number(v("x-quota")))
      && (v("x-category") === "" || r[R.CAT] === Number(v("x-category")))
      && (v("x-pwd") === "" || r[R.PWD] === Number(v("x-pwd")))
      && (!v("x-year") || src.year === Number(v("x-year")))
      && (!v("x-round") || src.round === v("x-round"));
  }).sort((a, b) => a[R.CLOSE] - b[R.CLOSE]);
  explorerShown = 100;
  renderExplorer();
});

function renderExplorer() {
  const el = document.getElementById("explorer-results");
  if (!explorerRows.length) {
    el.innerHTML = `<div class="empty-state">No rows match these filters.</div>`;
    return;
  }
  const body = explorerRows.slice(0, explorerShown).map(r => {
    const src = SOURCES[r[R.SRC]];
    return `<tr>
      <td>${src.year}<br><a class="dim" href="${esc(src.url)}" target="_blank" rel="noopener">${esc(src.round)}</a></td>
      <td>${instLabel(r[R.INST])}</td>
      <td>${esc(CUTOFFS.courses[r[R.COURSE]][0])}</td>
      <td>${esc(CUTOFFS.quotas[r[R.QUOTA]])}</td>
      <td>${esc(CUTOFFS.categories[r[R.CAT]])}${r[R.PWD] ? " <span class=\"pill\">PwD</span>" : ""}</td>
      <td class="num">${fmt(r[R.OPEN])}</td>
      <td class="num">${fmt(r[R.CLOSE])}</td>
      <td class="num">${r[R.SEATS]}</td>
    </tr>`;
  }).join("");
  el.innerHTML = `
    <p class="result-summary"><strong>${explorerRows.length.toLocaleString("en-IN")}</strong> rows, sorted by closing rank.
      <button type="button" class="chip" id="x-csv">⬇️ Download as CSV</button></p>
    <div class="table-scroll"><table class="result-table">
      <thead><tr><th>Year / Round</th><th>Institute</th><th>Course</th><th>Quota</th><th>Seat category</th>
        <th class="num">Opening</th><th class="num">Closing</th><th class="num">Allotted</th></tr></thead>
      <tbody>${body}</tbody>
    </table></div>
    ${explorerRows.length > explorerShown ? `<button type="button" class="chip more-btn" id="x-more">Show ${Math.min(100, explorerRows.length - explorerShown)} more</button>` : ""}`;
  const more = document.getElementById("x-more");
  if (more) more.addEventListener("click", () => { explorerShown += 100; renderExplorer(); });
  document.getElementById("x-csv").addEventListener("click", downloadExplorerCsv);
}

function downloadExplorerCsv() {
  const q = s => `"${String(s ?? "").replace(/"/g, '""')}"`;
  const lines = [["year", "round", "institute", "city", "state", "course", "program", "specialty", "quota", "seat_category", "pwd", "opening_rank", "closing_rank", "allotted", "source_pdf"].join(",")];
  for (const r of explorerRows) {
    const src = SOURCES[r[R.SRC]], [name, city, state] = CUTOFFS.institutes[r[R.INST]], c = CUTOFFS.courses[r[R.COURSE]];
    lines.push([src.year, q(src.round), q(name), q(city), q(state), q(c[0]), q(c[1]), q(c[2]), q(CUTOFFS.quotas[r[R.QUOTA]]),
      CUTOFFS.categories[r[R.CAT]], r[R.PWD], r[R.OPEN], r[R.CLOSE], r[R.SEATS], q(src.url)].join(","));
  }
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([lines.join("\n")], { type: "text/csv" }));
  a.download = "neet-pg-cutoffs.csv";
  a.click();
  URL.revokeObjectURL(a.href);
}

