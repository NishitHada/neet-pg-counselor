document.getElementById("predictor-form").addEventListener("submit", e => {
  e.preventDefault();
  const rank = Number(document.getElementById("p-rank").value);
  const cat = Number(document.getElementById("p-category").value);
  const pwd = document.getElementById("p-pwd").value === "yes";
  const quotaSel = document.getElementById("p-quota").value;
  const program = document.getElementById("p-program").value;
  const specialty = document.getElementById("p-specialty").value;
  const state = document.getElementById("p-state").value;
  const year = Number(document.getElementById("p-year").value);

  const aiq = CUTOFFS.quotas.indexOf("All India");
  const quotaOk = q => quotaSel === "aiq" ? q === aiq
    : quotaSel === "all" ? PREDICTABLE_QUOTAS.some(([, i]) => i === q)
    : q === Number(quotaSel);
  const rounds = ROUND_ORDER.filter(r => CUTOFFS.sources.some(s => s.year === year && s.round === r));

  // seat key -> { round -> best (highest) closing rank among the seat categories this candidate can take }
  const seats = new Map();
  for (const r of CUTOFFS.rows) {
    const src = SOURCES[r[R.SRC]];
    if (src.year !== year) continue;
    if (r[R.CAT] !== 0 && r[R.CAT] !== cat) continue;       // Open seats + own category
    if (r[R.PWD] && !pwd) continue;                          // PwD seats only for PwD candidates
    if (!quotaOk(r[R.QUOTA])) continue;
    if (!courseMatches(r[R.COURSE], program, specialty)) continue;
    if (state && CUTOFFS.institutes[r[R.INST]][2] !== state) continue;
    const key = `${r[R.INST]}|${r[R.COURSE]}|${r[R.QUOTA]}`;
    let s = seats.get(key);
    if (!s) seats.set(key, s = { inst: r[R.INST], course: r[R.COURSE], quota: r[R.QUOTA], close: {} });
    s.close[src.round] = Math.max(s.close[src.round] || 0, r[R.CLOSE]);
  }

  const reachable = [];
  for (const s of seats.values()) {
    const within = rounds.filter(rd => s.close[rd] >= rank);
    if (!within.length) continue;
    s.firstRound = within[0];
    s.sortKey = Math.min(...within.map(rd => s.close[rd]));
    reachable.push(s);
  }
  // Tightest fit first: seats whose closing rank was just above yours are the most competitive ones in reach.
  reachable.sort((a, b) => a.sortKey - b.sortKey);
  renderPredictorResults(reachable, rank, year, rounds, seats.size);
});

let predictorShown = 100;
function renderPredictorResults(rows, rank, year, rounds, considered, keepCount) {
  if (!keepCount) predictorShown = 100;
  const container = document.getElementById("predictor-results");
  if (rows.length === 0) {
    container.innerHTML = `<div class="empty-state">In ${year}, none of the ${considered.toLocaleString("en-IN")} matching seats
      went to anyone ranked ${fmt(rank)} or worse, in any round. Try another year, quota, program or state.</div>`;
    return;
  }
  const byRound = {};
  rows.forEach(s => byRound[s.firstRound] = (byRound[s.firstRound] || 0) + 1);
  const summary = rounds.filter(r => byRound[r]).map(r => `${byRound[r].toLocaleString("en-IN")} first reachable in ${r}`).join(" · ");
  const body = rows.slice(0, predictorShown).map(s => `
    <tr>
      <td>${instLabel(s.inst)}</td>
      <td>${esc(CUTOFFS.courses[s.course][0])}</td>
      <td>${esc(CUTOFFS.quotas[s.quota])}</td>
      ${rounds.map(rd => `<td class="num ${s.close[rd] >= rank ? "ok" : s.close[rd] ? "miss" : ""}">${fmt(s.close[rd])}</td>`).join("")}
    </tr>`).join("");
  container.innerHTML = `
    <p class="result-summary"><strong>${rows.length.toLocaleString("en-IN")}</strong> of ${considered.toLocaleString("en-IN")}
      matching seats were allotted at or beyond rank ${fmt(rank)} in ${year}. ${summary}.</p>
    <div class="table-scroll"><table class="result-table">
      <thead><tr><th>Institute</th><th>Course</th><th>Quota</th>${rounds.map(r => `<th class="num">${r}<br><span class="dim">closing</span></th>`).join("")}</tr></thead>
      <tbody>${body}</tbody>
    </table></div>
    ${rows.length > predictorShown ? `<button type="button" class="chip more-btn" id="p-more">Show ${Math.min(100, rows.length - predictorShown)} more</button>` : ""}
    <p class="note">"—" means no one in your eligible categories was allotted that seat in that round.
    That usually means it was already filled, or wasn't offered in that category. Closing ranks move year to year with
    seat matrices and candidate counts, so compare a few years before relying on one.</p>`;
  const more = document.getElementById("p-more");
  if (more) more.addEventListener("click", () => {
    predictorShown += 100;
    renderPredictorResults(rows, rank, year, rounds, considered, true);
  });
}

