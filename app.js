/* ---------- Cutoff data (data/cutoffs.js, generated by pipeline/normalize.py) ----------
   CUTOFFS.rows: [source_id, quota_idx, institute_idx, course_idx, category_idx, pwd, opening, closing, seats] */
const R = { SRC: 0, QUOTA: 1, INST: 2, COURSE: 3, CAT: 4, PWD: 5, OPEN: 6, CLOSE: 7, SEATS: 8 };
const SOURCES = Object.fromEntries(CUTOFFS.sources.map(s => [s.id, s]));
const YEARS = [...new Set(CUTOFFS.sources.map(s => s.year))].sort((a, b) => b - a);
const ROUND_ORDER = ["Round 1", "Round 2", "Round 3", "Mop-Up", "Stray Vacancy", "Special Stray"];
// Armed Forces seats are ranked by AFMS merit, not NEET rank, so they can't be predicted from a NEET rank.
const PREDICTABLE_QUOTAS = CUTOFFS.quotas.map((q, i) => [q, i]).filter(([q]) => q !== "Armed Forces");
const STATES = [...new Set(CUTOFFS.institutes.map(i => i[2]).filter(Boolean))].sort();
const PROGRAMS = [...new Set(CUTOFFS.courses.map(c => c[1]).filter(Boolean))];
const SPECIALTIES = [...new Set(CUTOFFS.courses.map(c => c[2]))].sort();

const esc = s => String(s ?? "").replace(/[&<>"]/g, ch => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[ch]));
const fmt = n => n == null ? "—" : n.toLocaleString("en-IN");
const instLabel = i => {
  const [name, city, state] = CUTOFFS.institutes[i];
  return `<strong>${esc(name)}</strong><br><span class="dim">${esc([city, state].filter(Boolean).join(", "))}</span>`;
};

